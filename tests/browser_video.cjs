const {launchBrowser}=require('./browser_helpers.cjs');
const assert=require('node:assert/strict');
const path=require('node:path');
const qa=path.resolve('.qa'),base='http://127.0.0.1:8766';
let browser,page,originalSettings,originalSemantic;
async function api(route,method='GET',body){const response=await fetch(base+'/api'+route,{method,headers:body?{'Content-Type':'application/json'}:{},body:body?JSON.stringify(body):undefined});assert.ok(response.ok,await response.clone().text());return response.json();}
async function until(predicate,timeout=60000){const end=Date.now()+timeout;while(Date.now()<end){if(await predicate())return;await new Promise(r=>setTimeout(r,200));}throw new Error('Timed out waiting for video UI');}
(async()=>{
 originalSettings=await api('/settings');assert.equal(originalSettings.data_dir,path.join(qa,'data'),'Only the QA library may be modified');
 originalSemantic=(await api('/semantic')).config;
 await api('/settings','PUT',{roots:[...originalSettings.roots,path.join(qa,'video-source')],comfy_url:originalSettings.comfy_url});
 await until(async()=> (await api('/images?media_kind=video')).total===3);
 const global=(await api('/images?unique_prompts=true&media_kind=video&prompt_scope=global')).items;
 assert.equal(global.length,1);assert.equal(global[0].image_count,3);
 const semantic = process.env.GALLERY_TEST_SEMANTIC === '1';
 await api('/semantic/settings','PUT',{...originalSemantic,enabled:semantic,model:'bge-small'});
 if(semantic) {
  const blue=(await api('/images?unique_prompts=true&media_kind=video&q=blue%20lake')).items[0];
  await until(async()=>{const value=await api('/prompts/'+blue.prompt_id+'/similar-prompts');if(value.semantic.state==='error')throw new Error(value.semantic.error);return value.items.some(i=>i.semantic_similarity!==null);});
 }
 browser=await launchBrowser();
 page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];let generationRequests=0;page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/\/queue$/.test(r.url()))generationRequests++;});
 await page.goto(base);await page.getByRole('button',{name:'Filters',exact:true}).click();
 await page.getByLabel('Media type',{exact:true}).selectOption('video');
 await page.waitForFunction(()=>document.querySelectorAll('.image-card').length===3);
 await page.screenshot({path:path.join(qa,'videos-desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'Inspect director_a.mp4',exact:true}).click();
 let detail=page.getByRole('dialog',{name:'director_a.mp4',exact:true});
 await page.waitForFunction(()=>document.querySelector('video')?.readyState>=1);
 assert.equal(await detail.locator('.video-prompt-document').count(),3);
 assert.match(await detail.locator('.video-prompt-document').first().innerText(),/Global prompt/);
 await page.locator('video').evaluate(async v=>{v.muted=true;await v.play();});
 await page.waitForFunction(()=>document.querySelector('video')?.currentTime>.2);
 await page.locator('video').evaluate(v=>v.pause());
 await detail.locator('.video-prompt-document').filter({has:page.getByRole('heading',{name:'Shot 2',exact:true})}).getByRole('button',{name:'Seek to shot',exact:true}).click();
 await page.waitForFunction(()=>Math.abs(document.querySelector('video').currentTime-1)<.15);
 await page.screenshot({path:path.join(qa,'video-details-desktop.png'),fullPage:true});
 await detail.getByRole('button',{name:'Metadata',exact:true}).click();
 assert.match(await detail.locator('.metadata-summary').innerText(),/ltx-director/);
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:/^Prompt library/}).click();
 await page.getByRole('textbox',{name:'Search library'}).fill('blue lake');
 await page.waitForFunction(()=>document.querySelectorAll('.prompt-group-card').length===1);
 assert.match(await page.locator('.prompt-scope-label').innerText(),/Shot prompt/);
 await page.getByRole('button',{name:'Expand prompt',exact:true}).click();
 await until(async()=> (await page.locator('.prompt-group-text').textContent())==='A fox runs toward a blue lake.');
 await page.getByRole('button',{name:'Find similar prompts',exact:true}).click();
 const related=page.getByRole('dialog',{name:'Similar prompts',exact:true});
 const green=related.locator('.similar-result').filter({hasText:'green lake'});
 await green.getByRole('button',{name:'Compare variation',exact:true}).click();
 const diff=page.getByRole('dialog',{name:'Compare prompts',exact:true});
 await diff.locator('.diff-removed').first().waitFor();
 assert.equal(await diff.locator('.diff-before .prompt-diff-text').textContent(),'A fox runs toward a blue lake.');
 assert.equal(await diff.locator('.diff-added').textContent(),'green');
 await page.screenshot({path:path.join(qa,'video-shot-diff-desktop.png'),fullPage:true});
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Clear prompt comparison selection',exact:true}).click();
 await page.getByRole('textbox',{name:'Search library'}).fill('director_a.mp4');
 await page.waitForFunction(()=>document.querySelectorAll('.prompt-group-card').length===3);
 const sameVideoShots=page.locator('.prompt-group-card').filter({hasText:'Shot prompt'});
 assert.equal(await sameVideoShots.count(),2);
 await sameVideoShots.nth(0).getByRole('button',{name:'Select prompt for comparison',exact:true}).click();
 await sameVideoShots.nth(1).getByRole('button',{name:'Select prompt for comparison',exact:true}).click();
 await page.getByRole('button',{name:'Compare prompts',exact:true}).click();
 await diff.locator('.prompt-diff-panel').first().waitFor();
 assert.ok(!(await diff.locator('.prompt-diff-columns').innerText()).includes('Video QA woodland continuity.'));
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:/^All media/}).click();
 await page.getByRole('button',{name:'Inspect director_proxy.mkv',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('video')?.readyState>=1);
 assert.match(await page.locator('.video-note').innerText(),/cached compatible copy/);
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 await page.screenshot({path:path.join(qa,'video-details-mobile.png'),fullPage:true});
 assert.equal(generationRequests,0);assert.deepEqual(errors,[]);
 console.log('Video browser checks passed: native playback and time advancement, seek to shot, global/shot separation, scoped search, '+(semantic?'BGE':'text')+' shot similarity, exact variation diff, compatible MKV proxy playback, metadata provenance, desktop/mobile, no generation requests.');
})().catch(async error=>{console.error(error);if(page)await page.screenshot({path:path.join(qa,'video-error.png'),fullPage:true}).catch(()=>{});process.exitCode=1;}).finally(async()=>{
 if(originalSemantic)await api('/semantic/settings','PUT',{...originalSemantic,enabled:false}).catch(()=>{});
 if(originalSettings)await api('/settings','PUT',{roots:originalSettings.roots,comfy_url:originalSettings.comfy_url}).catch(()=>{});
 await browser?.close();
});
