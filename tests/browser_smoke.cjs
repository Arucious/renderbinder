const {launchBrowser}=require('./browser_helpers.cjs');
const path=require('node:path');
const fs=require('node:fs');
const assert=require('node:assert/strict');
let qaBrowser,qaPage;
(async()=>{
  const browser=await launchBrowser();
  qaBrowser=browser;
  const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write'],acceptDownloads:true});
  const page=await context.newPage();
  qaPage=page;
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const dir=path.resolve('.qa');fs.mkdirSync(dir,{recursive:true});
  const base='http://127.0.0.1:8766';
  const get=async(p,method='GET',body)=>{const r=await fetch(base+'/api'+p,{method,headers:body?{'Content-Type':'application/json'}:{},body:body?JSON.stringify(body):undefined});assert.ok(r.ok,await r.clone().text());return r.json();};
  const config=await get('/settings');assert.equal(config.data_dir,path.resolve('.qa/data'),'This test may only reset the isolated QA data directory');
  const existing=await get('/images');
  if(existing.items.length)await get('/annotations','PATCH',{image_ids:existing.items.map(i=>i.id),favorite:false,tags:[]});
  for(const collection of (await get('/facets')).collections)await get('/collections/'+collection.id,'DELETE');
  await get('/settings','PUT',{roots:[],comfy_url:'http://127.0.0.1:8188'});
  for(let n=0;n<50;n++){if((await get('/images')).total===0)break;await new Promise(r=>setTimeout(r,100));}
  await page.goto(base);await page.getByRole('heading',{name:'No image folders configured'}).waitFor();
  await page.screenshot({path:path.join(dir,'empty-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Add image folder'}).click();
  await page.getByLabel('Image directories').fill(path.resolve('.qa/sources'));
  await page.getByRole('button',{name:'Save & scan folders'}).click();
  await page.getByRole('button',{name:'Inspect alpine_stillness_00001.png'}).waitFor();
  await page.waitForFunction(()=>document.querySelectorAll('.image-card').length===12);
  await page.screenshot({path:path.join(dir,'gallery-desktop.png'),fullPage:true});
  assert.equal(await page.locator('.image-card').count(),12);
  // Original source spelling (including a capital drive letter) must filter correctly.
  await page.locator('.source-root').click();
  await page.waitForTimeout(500);assert.equal(await page.locator('.image-card').count(),12);
  await page.getByRole('button',{name:'Inspect alpine_stillness_00001.png'}).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('dialog').getByRole('button',{name:'Settings',exact:true}).click();
  await page.getByText('18446744073709551615',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Copy seed',exact:true}).click();
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),'18446744073709551615');
  await page.screenshot({path:path.join(dir,'details-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Add favorite',exact:true}).click();
  await page.getByLabel('Tags',{exact:true}).fill('inspiration, cabin');
  await page.getByRole('button',{name:'Save tags',exact:true}).click();
  await page.getByRole('button',{name:'Raw JSON',exact:true}).click();
  assert.ok((await page.locator('.raw-json').textContent()).includes('18446744073709551615'));
  const downloadPromise=page.waitForEvent('download');await page.getByRole('link',{name:'Workflow',exact:true}).click();
  const download=await downloadPromise;await download.saveAs(path.join(dir,'workflow.json'));
  assert.equal(JSON.parse(fs.readFileSync(path.join(dir,'workflow.json'))).test_fixture,true);
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.getByRole('textbox',{name:'Search library'}).fill('inspiration');
  await page.waitForTimeout(650);assert.equal(await page.locator('.image-card').count(),1);
  await page.getByRole('button',{name:'Clear search',exact:true}).click();
  await page.waitForTimeout(600);
  await page.getByRole('button',{name:'Create collection',exact:true}).click();
  await page.getByLabel('Collection name').fill('QA favorites');
  await page.getByRole('button',{name:'Create collection',exact:true}).last().click();
  await page.waitForTimeout(300);
  await page.getByRole('button',{name:'Select alpine_stillness_00001.png',exact:true}).click({force:true});
  await page.getByRole('button',{name:'Select amber_horizon_00002.png',exact:true}).click({force:true});
  await page.getByRole('combobox',{name:'Add selection to collection'}).selectOption({label:'QA favorites'});
  await page.getByRole('button',{name:'Compare',exact:true}).click();
  await page.locator('.compare-table').waitFor();
  assert.ok(await page.locator('.compare-table .differs').count()>0);
  await page.screenshot({path:path.join(dir,'compare-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Close dialog',exact:true}).click();
  await page.getByRole('button',{name:'Clear selection',exact:true}).click();
  await page.getByRole('button',{name:'Done selecting',exact:true}).click();
  await page.getByRole('button',{name:'List view',exact:true}).click();
  await page.screenshot({path:path.join(dir,'list-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'Grid view',exact:true}).click();
  await page.getByRole('button',{name:'Filters',exact:true}).click();
  await page.getByLabel('Model',{exact:true}).selectOption('flux-dev.safetensors');
  await page.waitForTimeout(500);assert.equal(await page.locator('.image-card').count(),4);
  await page.getByRole('button',{name:'Reset filters',exact:true}).click();
  await page.getByRole('button',{name:'Filters',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(300);assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:path.join(dir,'gallery-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'Open navigation',exact:true}).click();
  await page.getByRole('button',{name:/Favorites/}).first().click();
  await page.waitForTimeout(500);assert.equal(await page.locator('.image-card').count(),1);
  await page.getByRole('button',{name:'Inspect alpine_stillness_00001.png'}).click();
  await page.getByRole('button',{name:'Copy positive prompt',exact:true}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:path.join(dir,'details-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Browser smoke passed: sources, source filter, 12 thumbnails, exact seed clipboard, favorites, tags, raw JSON, workflow download, search, collections, comparison, list view, model filters, mobile layout.');
  await browser.close();
})().catch(async e=>{console.error(e);if(qaPage){await qaPage.screenshot({path:path.resolve('.qa/browser-error.png'),fullPage:true}).catch(()=>{});fs.writeFileSync(path.resolve('.qa/browser-error.txt'),await qaPage.locator('body').innerText().catch(()=>''));}await qaBrowser?.close();process.exit(1);});
